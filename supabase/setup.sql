
create extension if not exists pgcrypto;

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  student_number int not null check (student_number between 1 and 31),
  question_number int not null check (question_number in (1,2)),
  question_text text not null,
  rule text not null,
  formula_solution text not null,
  correct_answer numeric not null,
  unique(student_number,question_number)
);

create table if not exists public.submissions (
  id uuid primary key default gen_random_uuid(),
  student_number int not null unique check (student_number between 1 and 31),
  correct_count int not null,
  incorrect_count int not null,
  score_percent numeric not null,
  submitted_at timestamptz not null default now()
);

create table if not exists public.submission_items (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null references public.submissions(id) on delete cascade,
  question_id bigint not null references public.questions(id),
  question_number int not null,
  question_text text not null,
  student_answer text not null,
  normalized_answer numeric,
  correct_answer numeric not null,
  is_correct boolean not null,
  rule text not null,
  formula_solution text not null
);

